// Config plugin: certificate pinning for the API host with each platform's built-in mechanism.
//
// - Android: Network Security Config <pin-set>. Enforced by the system trust manager, so it
//   covers every client in the app: expo/fetch, React Native fetch/WebSocket and the native
//   file uploader (they all use OkHttp with the default trust manager).
// - iOS: App Transport Security NSPinnedDomains (CA identities). Applies to all URLSession
//   traffic, which is what expo/fetch and React Native's fetch use.
//
// Pinning libraries that hook React Native's networking would miss expo/fetch, which is
// this app's global fetch. Pins and rotation: config/pins.js, docs/certificate-pinning.md.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withInfoPlist } = require('expo/config-plugins');

const XML_NAME = 'network_security_config';

function androidXml(host, pins, expiration) {
  const lines = pins.map((p) => `      <!-- ${p.name} -->\n      <pin digest="SHA-256">${p.spki}</pin>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withApiPinning.js from config/pins.js. Do not edit by hand. -->
<network-security-config>
  <domain-config>
    <domain includeSubdomains="false">${host}</domain>
    <pin-set expiration="${expiration}">
${lines}
    </pin-set>
  </domain-config>
</network-security-config>
`;
}

function withAndroidPinning(config, { host, pins, expiration }) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${XML_NAME}.xml`), androidXml(host, pins, expiration));
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = `@xml/${XML_NAME}`;
    return cfg;
  });
}

function withIosPinning(config, { host, pins }) {
  return withInfoPlist(config, (cfg) => {
    const ats = cfg.modResults.NSAppTransportSecurity ?? {};
    // Release builds: no plain-HTTP loads anywhere (the template allows them for Metro in development).
    ats.NSAllowsArbitraryLoads = false;
    ats.NSPinnedDomains = {
      ...(ats.NSPinnedDomains ?? {}),
      [host]: {
        NSIncludesSubdomains: false,
        NSPinnedCAIdentities: pins.map((p) => ({ 'SPKI-SHA256-BASE64': p.spki })),
      },
    };
    cfg.modResults.NSAppTransportSecurity = ats;
    return cfg;
  });
}

/** @param {{ host: string, pins: {name: string, spki: string}[], expiration: string }} options */
module.exports = function withApiPinning(config, options) {
  if (!options?.host || !options.pins?.length) throw new Error('withApiPinning needs a host and pins');
  if (options.pins.length < 2) throw new Error('Pin at least two keys (a backup), or a CA change locks users out');
  return withIosPinning(withAndroidPinning(config, options), options);
};
